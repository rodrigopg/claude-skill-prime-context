def command_output(command, cwd):
    # Keep the pipe unbuffered so closing it on timeout does not wait for a
    # redirected Windows child to release a Python buffer lock.
    with subprocess.Popen(
        command, shell=True, cwd=cwd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL, bufsize=0,
    ) as process:
        try:
            stdout, _ = process.communicate(timeout=20)
        except subprocess.TimeoutExpired:
            process.kill()
            raise
        if process.returncode:
            raise subprocess.CalledProcessError(process.returncode, command)
    return stdout


def source_data(shared):
    digest = hashlib.sha256()
    sections = []
    seen = set()
    errors = []
    warnings = []
    secrets = False

    def inspect(source, raw, ancestors=()):
        nonlocal secrets
        digest.update(len(raw).to_bytes(8, "big"))
        digest.update(raw)
        text = raw.decode("utf-8")
        for line_number, content in enumerate(text.splitlines(), 1):
            if secret_on(content):
                print(f"{source}:{line_number}: secret", file=sys.stderr)
                secrets = True
        if not isinstance(source, Path):
            return text
        lines = text.splitlines(keepends=True)
        canonical = source.resolve()
        ancestors = (*ancestors, canonical)
        # Expand in reading order, then replace spans from right to left.
        replacements = []
        for number, (start, end), _, path in imports(text, canonical.parent):
            if path in ancestors:
                replacements.append((number, start, end, ""))
                continue
            try:
                if not path.is_file():
                    raise OSError("not a regular file")
                if len(ancestors) > 5:
                    expanded = ""
                else:
                    expanded = "\n" + inspect(path, path.read_bytes(), ancestors).rstrip("\r\n") + "\n"
                replacements.append((number, start, end, expanded))
            except (OSError, UnicodeError):
                errors.append(f"{source}:{number + 1}: cannot read imported file {path}")
        for number, start, end, expanded in reversed(replacements):
            lines[number] = lines[number][:start] + expanded + lines[number][end:]
        return "".join(lines)

    source_list = shared / "sources.list"
    try:
        lines = read(source_list).splitlines()
    except (OSError, UnicodeError):
        return "", [], ["Cannot read sources.list as UTF-8"], warnings, False
    for number, line in enumerate(lines, 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        label = f"sources.list:{number}"
        kind, *args = line.split(maxsplit=1)
        if not args or kind not in ("file", "glob", "cmd"):
            errors.append(f"{label}: invalid source entry")
            continue
        if kind == "cmd":
            try:
                inputs = [(label, command_output(args[0], shared))]
            except (OSError, ValueError, subprocess.SubprocessError):
                warnings.append(f"{label}: command source failed")
                continue
        else:
            try:
                pattern = shared / Path(args[0]).expanduser()
                paths = [pattern] if kind == "file" else map(Path, sorted(glob(str(pattern))))
            except (OSError, RuntimeError, ValueError):
                errors.append(f"{label}: cannot resolve file source")
                continue
            inputs = []
            for path in paths:
                try:
                    canonical = path.resolve()
                    if canonical in seen:
                        continue
                    if not path.is_file():
                        raise OSError("not a regular file")
                    inputs.append((path, path.read_bytes()))
                    seen.add(canonical)
                except (OSError, RuntimeError, ValueError):
                    errors.append(f"{label}: cannot read file source {path}")
        for source, raw in inputs:
            try:
                text = inspect(source, raw)
            except UnicodeError:
                if kind == "cmd":
                    warnings.append(f"{label}: command source is not UTF-8")
                else:
                    errors.append(f"{label}: file source is not UTF-8: {source}")
                continue
            sections.append("".join(map(redact_phone, text.splitlines(keepends=True))).rstrip("\r\n"))
    return digest.hexdigest(), sections, errors, warnings, secrets


def target_hash(target):
    if not target.is_file():
        return None
    with target.open("rb") as stream:
        header = stream.readline().decode("utf-8", errors="replace").rstrip("\r\n")
    match = HEADER_HASH.fullmatch(header)
    return match[1] if match else None


def sync(shared, claude, args):
    digest, sections, errors, warnings, secrets = source_data(shared)
    for warning in warnings:
        warn(warning)
    for error in errors:
        print(f"ERROR: {error}", file=sys.stderr)
    if errors:
        return 1 if args.check else 2
    if secrets:
        return 3
    if args.strict and warnings:
        return 2
    unsafe = False
    for path, _, _, problems in shared_memory_violations(shared):
        unsafe = True
        for line, pattern in problems:
            print(f"{path}:{line}: {pattern}", file=sys.stderr)
    if unsafe:
        return 1
    status = 0
    targets = [target.expanduser() for target in args.target] if args.target else default_targets(shared)
    if args.check:
        for target in targets:
            if target_hash(target) != digest:
                print(f"Stale or missing target {target}")
                status = 1
        return status
    if deliver_rules(shared, claude, args.apply):
        return 2
    memory = (
        "## Shared memory\n\n"
        f"Global index: {shared / 'memory/MEMORY.md'}\n\n"
        "Project memory: use the prime-context skill's resolve mode or read "
        f"{shared / 'projects/INDEX.md'} and match the repository's normalized origin.\n\n"
        "Notes with metadata.share: claude-only are for Claude Code only. "
        "Other harnesses must skip them.\n"
    )
    header = f"{HEADER}{shared.as_posix()}/rules/ instead. sources-sha256={digest} -->"
    generated = "\n\n".join([header, *filter(None, sections), memory]).encode("utf-8")
    for target in targets:
        print(f"Generate {target}")
        if args.apply and (not target.is_file() or target.read_bytes() != generated):
            atomic_write(target, generated, backup=target_hash(target) is None)
    return 0


def precompact(claude, cwd, finding):
    commands = []
    count = 0
    enabled = os.environ.get("PRIME_CONTEXT_COMPACTION") == "1"
    settings_paths = (claude / "settings.json", cwd / ".claude/settings.json", cwd / ".claude/settings.local.json")
    for path in dict.fromkeys(path.resolve() for path in settings_paths):
        if not path.is_file():
            continue
        try:
            settings = json.loads(read(path))
            groups = settings.get("hooks", {}).get("PreCompact", [])
            hooks = [hook for group in groups for hook in group.get("hooks", [])]
            configured_commands = [hook["command"] for hook in hooks if hook.get("type") == "command"]
            if any(not isinstance(command, str) for command in configured_commands):
                raise TypeError("invalid PreCompact command")
            enabled = enabled or str(settings.get("env", {}).get("PRIME_CONTEXT_COMPACTION", "")) == "1"
            count += len(hooks)
            commands.extend(configured_commands)
        except (ValueError, TypeError, AttributeError, KeyError, OSError):
            finding("MED", f"Invalid settings in {path}", "repair the settings JSON")
    if count > 1:
        finding("MED", "More than one PreCompact hook is configured", "keep one compaction policy")
    own_hook = "${CLAUDE_PLUGIN_ROOT}/hooks/pre_compact.py"
    own_command = re.compile(r'\s*python3\s+"?' + re.escape(own_hook) + r'"?\s*')
    if enabled and any(not own_command.fullmatch(cmd.replace("\\", "/")) for cmd in commands if cmd):
        finding("HIGH", "Prime Context and another PreCompact command are configured", "replace the other policy")


def check_memory(index, finding):
    if not index.is_file():
        finding("HIGH", f"Missing memory index {index}", "restore or recreate the memory index")
    for target in pointer_targets(read_optional(index)):
        if not (index.parent / target).is_file():
            finding("HIGH", f"Dead memory pointer {target} in {index}", "restore the note or fix the pointer")
    for note, text in memory_documents(index.parent):
        if note == index or note.suffix.lower() not in (".md", ".markdown"):
            continue
        values, legacy = metadata(text)
        if legacy or not values.get("type"):
            message = "Legacy top-level type in" if legacy else "Missing metadata.type in"
            finding("LOW", f"{message} {note}", "set metadata.type in the frontmatter")


def check_copies(shared, claude, entries, finding):
    fix = "review the copies and point Claude at the shared version"
    for rule in sorted((claude / "rules").glob("*.md")):
        if not rule.is_file():
            continue
        target = shared / "rules" / rule.name
        if not target.is_file() or rule_conflict(rule, target):
            finding("MED", f"Claude rule diverges: {rule}", fix)
    project_root = claude / "projects"
    state = json.loads(read_optional(shared / MIGRATION_STATE) or "{}")
    binding = global_sources(shared, claude).get(str(claude.resolve()))
    global_path = Path(binding) if binding else project_root / project_folder(Path.home())
    _, mappings = project_maps(shared, claude)
    audited = json.loads(read_optional(shared / AUDIT_MAPS) or "{}").get(str(claude.resolve()), {})
    selected_global = global_path.resolve()
    unmapped = []
    for directory in memory_project_directories(project_root, global_path):
        source = directory / "memory"
        try:
            mapping = mappings.get(directory.name) if directory.parent == project_root else None
            identity = directory.resolve()
            if identity != selected_global and not mapping and str(identity) in audited:
                key = audited[str(identity)]
            else:
                key = transcript_project(shared, directory, global_path, mapping)
        except ValueError:
            unmapped.append(directory.name)
            continue
        if key is None:
            index = shared / "memory/MEMORY.md"
        else:
            if key not in entries:
                continue
            index = shared / "projects" / entries[key]
        if source.is_symlink() and not same_location(source, index.parent):
            unmapped.append(directory.name)
            continue
        if same_link(source, index.parent):
            continue
        shared_targets = set(pointer_targets(read_optional(index)))
        names = {}
        for note, kind in memory_tree(source):
            relative = note.relative_to(source).as_posix()
            if relative == "MEMORY.md":
                continue
            if kind == "directory":
                if not (index.parent / relative).is_dir():
                    break
                continue
            if kind == "link" and (index.parent / relative).is_symlink():
                continue
            if kind != "file":
                break
            data, violations, _ = memory_payload(note)
            if violations:
                break
            saved = state.get(str(note.resolve()), {}).get("target")
            original = index.parent / relative
            digest = hashlib.sha256(data).hexdigest()
            candidates = [shared / saved] if saved else [
                original, *(collision_name(original, digest, length) for length in range(8, len(digest) + 1))
            ]
            target = next((p for p in candidates if index.parent in p.parents and p.is_file()
                           and p.read_bytes() == data), None)
            if target is None:
                break
            names[relative] = target.relative_to(index.parent).as_posix()
        else:
            local_text = read_optional(source / "MEMORY.md")
            local_targets = {names.get(link, link) for link in pointer_targets(local_text)}
            prose = "".join(line for line in local_text.splitlines(keepends=True) if not pointer(line.rstrip())[0])
            if local_targets <= shared_targets and redact_phone(prose).strip() in read_optional(index):
                continue
        finding("MED", f"Claude memory diverges: {source}", fix)
    if unmapped:
        finding("MED", f"{len(unmapped)} UNMAPPED Claude memory folder(s): {', '.join(unmapped)}",
                "use migrate --map or register --local-id for a project without an origin")


def doctor(shared, claude, json_output):
    findings = []

    def finding(severity, message, fix):
        findings.append(dict(severity=severity, message=message, fix=fix))

    cwd = Path.cwd()
    if not configured(shared):
        finding("HIGH", f"Missing or unsupported shared marker {shared / MARKER}; shared checks skipped",
                "restore the format=1 marker or run init --apply for a new store")
    else:
        digest, _, errors, warnings, secrets = source_data(shared)
        for error in errors:
            finding("HIGH", error, "restore the source and run sync --apply")
        for warning in warnings:
            finding("MED", warning, "repair the command source and run sync --check")
        for target in default_targets(shared):
            actual = target_hash(target)
            if actual is None or errors or secrets or (not warnings and actual != digest):
                finding("HIGH", f"Stale or missing target {target}", "run sync --apply after fixing source errors")
            if exists(target) and actual is None:
                severity = "HIGH" if target == shared / "AGENTS.md" else "MED"
                finding(severity, f"Target lacks the GENERATED header: {target}", "review it and run sync --apply")
        authored = shared / "rules/AGENTS.md"
        if not read_optional(authored).strip():
            finding("HIGH", f"Missing or empty authored rules: {authored}", "restore or write the authored rules")
        claude_main = claude / "CLAUDE.md"
        claude_imports = {path for _, _, _, path in imports(read_optional(claude_main), claude_main.resolve().parent)}
        if claude_main.resolve() != authored.resolve() and authored.resolve() not in claude_imports:
            finding("HIGH", f"Missing shared import in {claude_main}", "run migrate --apply")
        generated = (shared / "AGENTS.md").resolve()
        if generated == claude_main.resolve() or generated in claude_imports:
            finding("HIGH", f"{claude_main} imports the generated AGENTS.md", "import rules/AGENTS.md instead")
        for path in sorted(claude_imports):
            if not path.is_file():
                finding("HIGH", f"Missing import target in {claude_main}: {path}", "restore the import target")
        entries = projects(shared)
        try:
            origin = git_origin(cwd)
        except ValueError:
            finding("MED", "Current Git origin is unsupported", "use a supported origin")
            origin = None
        if origin and origin not in entries:
            finding("MED", f"Current project is not registered: {origin}", "run register --apply")
        check_memory(shared / "memory/MEMORY.md", finding)
        project_root = shared / "projects"
        indexes = {project_root / target for target in entries.values()}
        indexes.update(project_root.glob("*/MEMORY.md"))
        for index in sorted(indexes):
            check_memory(index, finding)
        for path, _, note, problems in shared_memory_violations(shared):
            for number, pattern in problems:
                fix = "run quarantine --apply or remove the sensitive value" if note else "remove the sensitive value"
                finding("HIGH", f"{path}:{number}: {pattern}", fix)
        check_copies(shared, claude, entries, finding)
    repository = git(cwd, "rev-parse", "--show-toplevel")
    precompact(claude, Path(repository) if repository else cwd, finding)
    if json_output:
        print(json.dumps(findings))
    else:
        for item in findings:
            print("{severity}: {message} — {fix}".format(**item))
        print(f"doctor: {len(findings)} findings" if findings else "doctor: clean")
    return int(any(item["severity"] == "HIGH" for item in findings))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="action", required=True)
    commands = {name: sub.add_parser(name) for name in (
        "init", "migrate", "sync", "register", "resolve", "check-note", "append-index", "doctor", "quarantine",
    )}
    for name in ("init", "migrate", "sync", "register", "append-index", "quarantine"):
        commands[name].add_argument("--apply", action="store_true", help="apply the printed plan")
    for name in ("migrate", "doctor", "sync"):
        commands[name].add_argument("--claude-home", type=Path)
    commands["migrate"].add_argument("--global-project", type=Path)
    commands["migrate"].add_argument("--map", action="append", default=[], metavar="CLAUDE-FOLDER=PATH")
    commands["sync"].add_argument("--check", action="store_true")
    commands["sync"].add_argument("--strict", action="store_true")
    commands["sync"].add_argument("--target", type=Path, action="extend", nargs="+")
    for name in ("register", "resolve"):
        commands[name].add_argument("path", type=Path, nargs="?", default=Path.cwd())
    commands["register"].add_argument("--local-id")
    commands["check-note"].add_argument("file", type=Path)
    commands["append-index"].add_argument("indexfile", type=Path)
    commands["append-index"].add_argument("line")
    commands["doctor"].add_argument("--json", action="store_true")
    commands["quarantine"].add_argument("--budget", type=float, help=argparse.SUPPRESS)
    argv = sys.argv[1:]
    if argv and argv[0] == "migrate":
        for index in range(len(argv) - 2, 0, -1):
            if argv[index] == "--map" and re.fullmatch(r"-[A-Za-z0-9-]*=.+", argv[index + 1]):
                argv[index:index + 2] = ["--map=" + argv[index + 1]]
    args = parser.parse_args(argv)
    try:
        shared = shared_home()
        if args.action in ("migrate", "sync", "register", "resolve", "quarantine") and not configured(shared):
            print("Shared context is not configured; run init --apply", file=sys.stderr)
            return 5
        if args.action == "init":
            init(shared, args.apply)
        elif args.action == "migrate":
            claude = args.claude_home or location("CLAUDE_CONFIG_DIR", Path.home() / ".claude")
            return migrate(shared, claude.expanduser().absolute(), args.global_project, args.map, args.apply)
        elif args.action == "sync":
            claude = args.claude_home or location("CLAUDE_CONFIG_DIR", Path.home() / ".claude")
            return sync(shared, claude.expanduser().absolute(), args)
        elif args.action == "quarantine":
            return quarantine(shared, args.apply, args.budget)
        elif args.action == "register":
            register(shared, args.path, args.local_id, args.apply)
        elif args.action == "resolve":
            return resolve(shared, args.path)
        elif args.action == "check-note":
            return check_note(args.file)
        elif args.action == "append-index":
            append_index(args.indexfile, args.line, args.apply)
        elif args.action == "doctor":
            claude = args.claude_home or location("CLAUDE_CONFIG_DIR", Path.home() / ".claude")
            return doctor(shared, claude.expanduser().absolute(), args.json)
    except UnicodeError:
        print("ERROR: a file could not be decoded or encoded as UTF-8", file=sys.stderr)
        return 2
    except subprocess.TimeoutExpired:
        print("ERROR: Git lookup timed out", file=sys.stderr)
        return 2
    except (OSError, ValueError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
