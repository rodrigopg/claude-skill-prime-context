def transcript_cwds(directory):
    transcripts = sorted(directory.glob("*.jsonl"))
    if not transcripts:
        raise ValueError("no transcripts")
    starts = Counter()
    skipped = 0
    for transcript in transcripts:
        first = None
        try:
            with transcript.open("rb") as stream:
                for line in stream:
                    if not line.strip():
                        continue
                    try:
                        record = json.loads(line)
                    except (UnicodeError, ValueError):
                        skipped += 1
                        continue
                    if isinstance(record, dict) and isinstance(record.get("cwd"), str) and record["cwd"]:
                        first = record["cwd"]
                        break
        except OSError:
            raise ValueError("unreadable transcript") from None
        if first:
            starts[first] += 1
    candidates = set()
    historical = 0
    for cwd, count in starts.items():
        path = Path(cwd)
        if project_folder(cwd) == directory.name and path.is_absolute() and path.is_dir():
            candidates.add(path.resolve())
        else:
            historical += count
    details = []
    if historical:
        details.append(f"{historical} historical transcript cwd(s) ignored (name mismatch or missing path)")
    if skipped:
        details.append(f"{skipped} invalid JSONL line(s) skipped")
    return candidates, "; ".join(details)


def project_key(shared, path):
    try:
        return git_origin(path) or local_key(shared, path)
    except ValueError:
        return local_key(shared, path)


def transcript_project(shared, directory, global_path, mapping=None, report=False):
    if directory.resolve() == global_path.resolve():
        return None
    if mapping is not None:
        path = Path(mapping)
        key = project_key(shared, path) if path.is_dir() else None
        if key is None:
            raise ValueError("explicit mapping needs an existing Git origin or registered local ID")
        return key
    cwds, detail = transcript_cwds(directory)
    if report and detail:
        print(f"NOTE: {directory.name}: {detail}", file=sys.stderr)
    if not cwds:
        raise ValueError("no matching existing cwd")
    keys = {project_key(shared, path) for path in cwds}
    if len(keys - {None}) > 1:
        raise ValueError("several origins or local IDs")
    if None in keys:
        raise ValueError("no supported Git origin or local ID")
    return keys.pop()


