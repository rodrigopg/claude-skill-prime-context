def migrated_link(source, target, directory, check=None):
    """Install the link after it is known to work and restore on replacement failure."""
    with tempfile.TemporaryDirectory(prefix=".prime-context-", dir=source.parent) as temp:
        link = Path(temp) / "link"
        link.symlink_to(target, target_is_directory=directory)
        backup = backup_name(source)
        source.rename(backup)
        try:
            if check is None or check(backup):
                link.replace(source)
                return True
        except (OSError, ValueError, RuntimeError):
            backup.rename(source)
            raise
        backup.rename(source)
        return False


def same_link(source, target):
    return source.is_symlink() and source.resolve() == target.resolve()


def same_location(source, target):
    return source.resolve() == target.resolve()


def rule_conflict(local, shared):
    return exists(local) and exists(shared) and not (
        local.is_file() and shared.is_file() and local.read_bytes() == shared.read_bytes()
    )


def deliver_rules(shared, claude, apply, extra=()):
    main = (claude / "CLAUDE.md").resolve()
    if main == (shared / "AGENTS.md").resolve():
        print("ERROR: Claude is linked to generated rules; run migrate --apply", file=sys.stderr)
        return True
    existing = main.read_bytes().decode("utf-8") if main.is_file() else ""
    imported = {target for _, _, _, target in imports(existing, main.parent)}
    fallback = []
    errors = False
    authored = shared / "rules/AGENTS.md"
    for rule in sorted(set((shared / "rules").glob("*.md")) | set(extra)):
        if not rule.is_file() and rule not in extra:
            continue
        local = claude / "rules" / rule.name
        if rule_conflict(local, rule):
            print(f"ERROR: merge rule by hand: {local} and {rule}", file=sys.stderr)
            errors = True
            continue
        if rule.resolve() == main or rule.resolve() in imported or same_location(local, rule):
            continue
        if rule == authored:
            fallback.append(rule)
            continue
        print(f"Link Claude rule {local} → {rule} (or import it if symlinks are unavailable)")
        if apply:
            try:
                local.parent.mkdir(parents=True, exist_ok=True)
                if exists(local):
                    migrated_link(local, rule.resolve(), False)
                else:
                    local.symlink_to(rule.resolve())
            except OSError:
                warn(f"Could not symlink {local}; using an import")
                fallback.append(rule)
    if fallback:
        for path in fallback:
            print(f"Add Claude import for {path}")
        if apply:
            separator = "\n" if existing and not existing.endswith("\n") else ""
            lines = "".join(import_line(path.resolve()) + "\n" for path in fallback)
            atomic_write(main, (existing + separator + lines).encode("utf-8"), backup=True)
    return errors


def add_rule_sources(shared, paths, apply):
    source_list = shared / "sources.list"
    content = read(source_list)
    existing = set()
    for line in content.splitlines():
        fields = line.split(maxsplit=1)
        if len(fields) == 2 and fields[0] == "file":
            existing.add((shared / Path(fields[1]).expanduser()).resolve())
    additions = sorted(set(paths) - existing)
    if additions:
        for path in additions:
            print(f"Add file source for retained Claude import {path}")
        if apply:
            separator = "\n" if content and not content.endswith("\n") else ""
            lines = "".join("file " + path.relative_to(shared.resolve()).as_posix() + "\n" for path in additions)
            atomic_write(source_list, (content + separator + lines).encode("utf-8"), backup=True)


def collision_name(path, digest, length=8):
    return path.with_name(f"{path.stem}-{digest[:length]}{path.suffix}")


def memory_tree(root):
    for path in sorted(root.iterdir()):
        if path.name.startswith(".prime-context-"):
            continue
        if path.is_symlink():
            yield path, "link"
        elif getattr(path.lstat(), "st_reparse_tag", None) == getattr(stat, "IO_REPARSE_TAG_MOUNT_POINT", -1):
            yield path, "unsupported"
        elif path.is_dir():
            yield path, "directory"
            yield from memory_tree(path)
        else:
            yield path, "file" if path.is_file() else "unsupported"


def memory_snapshot(source):
    snapshot = {}
    for path, kind in memory_tree(source):
        status = path.lstat()
        snapshot[path, kind] = status.st_mtime_ns, status.st_size
    return snapshot


def private_frontmatter(text):
    lines = text.splitlines(keepends=True)
    if lines and lines[0].strip() == "---":
        for end, line in enumerate(lines[1:], 1):
            if line.strip() == "---":
                break
        else:
            end = None
        if end is not None:
            for number, line in enumerate(lines[1:end], 1):
                key, separator, value = line.partition(":")
                if key != "metadata" or not separator or (value.strip() and not value.strip().startswith("#")):
                    continue
                indentation = None
                share_lines = []
                for offset, child in enumerate(lines[number + 1:end], number + 1):
                    if child.strip() and not child.lstrip().startswith("#"):
                        if not child[0].isspace():
                            break
                        if indentation is None:
                            indentation = child[:len(child) - len(child.lstrip())]
                        if child.startswith(indentation + "share:"):
                            share_lines.append(offset)
                if share_lines:
                    for share_line in reversed(share_lines[1:]):
                        del lines[share_line]
                    ending = "\r\n" if lines[share_lines[0]].endswith("\r\n") else "\n"
                    lines[share_lines[0]] = indentation + "share: claude-only" + ending
                    return "".join(lines)
                lines.insert(number + 1, (indentation or "  ") + "share: claude-only\n")
                return "".join(lines)
            lines.insert(end, "metadata:\n  share: claude-only\n")
            return "".join(lines)
    return "---\nmetadata:\n  share: claude-only\n---\n" + text


def memory_payload(path):
    data = path.read_bytes()
    text = memory_text(data)
    if text is None:
        return data, [], False
    if path.suffix.lower() not in (".md", ".markdown"):
        return data, list(note_violations(text, include_phone=True)), False
    violations = list(note_violations(text, include_phone=True))
    secrets = [(number, kind) for number, kind in violations if kind == "secret"]
    if secrets:
        return data, secrets, False
    is_private = (
        "share" not in metadata(text)[0]
        and any(kind == "phone" for _, kind in violations)
    )
    if not is_private:
        return data, [], False
    private = private_frontmatter(text)
    if metadata(private)[0].get("share") != "claude-only":
        return data, [(1, "cannot mark frontmatter Claude-only")], False
    return private.encode("utf-8", errors="surrogateescape"), [], True


class Migration:
    def __init__(self, shared, apply):
        self.shared = shared
        self.apply = apply
        self.state_file = shared / MIGRATION_STATE
        self.state = json.loads(read_optional(self.state_file) or "{}")
        self.before = self.state.copy()
        self.planned_notes = {}
        self.planned_dirs = set()
        self.planned_indexes = {}
        self.copied = 0
        self.pointers = 0
        self.collisions = 0
        self.mapped = 0
        self.unmapped = []
        self.link_warnings = []
        self.blocked = 0
        self.private = 0
        self.assets = 0
        self.subdirs = 0

    def copy(self, source, target, data, verify=None, memory=False):
        print(f"Copy {source} → {target}")
        if self.apply:
            backup = private_memory_backup(self.shared, target) if memory else None
            atomic_write(target, data, backup=True, verify=verify, private_backup=backup)
        else:
            self.planned_notes[target] = hashlib.sha256(data).hexdigest()
        self.copied += 1

    def save_state(self, verify):
        if self.apply and self.state != self.before:
            data = json.dumps(self.state, indent=2, sort_keys=True).encode("utf-8") + b"\n"
            atomic_write(self.state_file, data, backup=True, verify=verify)

    def link(self, source, target, directory=False, check=None):
        print(f"Replace {source} with symlink to {target} (keep backup)")
        if self.apply:
            try:
                return migrated_link(source, target, directory, check)
            except OSError:
                warn(f"Could not symlink {source}; check the original and shared copy")
                self.link_warnings.append(source)
        return True

    def rules(self, claude):
        entrypoint = claude / "CLAUDE.md"
        main = entrypoint.resolve()
        authored = self.shared / "rules/AGENTS.md"
        generated_target = (self.shared / "AGENTS.md").resolve()
        if main == generated_target:
            if not entrypoint.is_symlink() or rule_conflict(claude / "rules/AGENTS.md", authored):
                print("ERROR: separate Claude's entrypoint from the generated rules before migrating", file=sys.stderr)
                return True
            print(f"Redirect legacy Claude link {entrypoint} → {authored} (keep backup)")
            if not self.apply:
                return False
            migrated_link(entrypoint, authored.resolve(), False)
            main = entrypoint.resolve()
        import_rule = import_line(authored)
        raw = main.read_bytes() if main.is_file() else b""
        content = raw.decode("utf-8")
        original_imports = list(imports(content, main.parent))
        canonical = authored.resolve()
        shared_home = self.shared.resolve()
        retained_sources = [path for _, _, _, path in original_imports
                            if path not in (canonical, generated_target) and shared_home in path.parents and path.is_file()]
        add_rule_sources(self.shared, retained_sources, self.apply)
        generated_import = any(path == generated_target for _, _, _, path in original_imports)
        if main != canonical and not rule_conflict(claude / "rules/AGENTS.md", authored) and (
            generated_import or not any(path == canonical for _, _, _, path in original_imports)
        ):
            retained = ""
            if main.is_file() and main != canonical:
                lines = content.splitlines(keepends=True)
                without_shared = lines.copy()
                for number, (start, end), _, path in reversed(original_imports):
                    if shared_home in path.parents:
                        without_shared[number] = without_shared[number][:start] + without_shared[number][end:]
                shim = original_imports and not "".join(without_shared).strip()
                if generated_import or shim:
                    for number, (start, end), _, path in reversed(original_imports):
                        if path in (canonical, generated_target):
                            lines[number] = lines[number][:start] + lines[number][end:]
                    retained = "".join(line for line in lines if line.strip() != IMPORT_COMMENT).strip()
                elif content.strip():
                    for number, (start, end), original, path in reversed(original_imports):
                        if not original.is_absolute() and path.is_file():
                            print(f"Rewrite import in {main}:{number + 1} → {path}")
                            lines[number] = lines[number][:start] + import_line(path) + lines[number][end:]
                    data = "".join(lines).encode("utf-8")
                    previous = authored.read_bytes() if authored.is_file() else b""
                    if previous.strip() and previous != data:
                        data = previous.rstrip(b"\r\n") + b"\n\n" + data
                    if previous != data:
                        self.copy(main, authored, data)
            print(f"Set shared import in {main} (back up any existing file)")
            if self.apply:
                replacement = import_rule + "\n" + IMPORT_COMMENT + "\n"
                if retained:
                    replacement += "\n" + retained + "\n"
                atomic_write(main, replacement.encode("utf-8"), backup=True)
        copied = []
        for source in sorted((claude / "rules").glob("*.md")):
            target = authored.parent / source.name
            if not source.is_file() or same_location(source, target):
                continue
            if not exists(target):
                self.copy(source, target, source.read_bytes())
                copied.append(target)
        return deliver_rules(self.shared, claude, self.apply, copied)

    def target_digest(self, target):
        if target in self.planned_notes:
            return self.planned_notes[target]
        if target.is_file() and not target.is_symlink():
            return hashlib.sha256(target.read_bytes()).hexdigest()
        return "" if exists(target) or target in self.planned_dirs else None

    def unique_copy(self, path, digest):
        for length in range(8, len(digest) + 1):
            target = collision_name(path, digest, length)
            if self.target_digest(target) in (None, digest):
                return target
        raise ValueError(f"file collision cannot be resolved at {path}")

    def copy_note(self, source, root, destination, data, verify):
        relative = source.relative_to(root)
        original = destination / relative
        digest = hashlib.sha256(data).hexdigest()
        key = str(source.resolve())
        saved = self.state.get(key, {})
        previous = saved.get("target")
        target = self.shared / previous if previous else original
        owned = previous is not None and target.parent == original.parent and not target.is_symlink()
        owned = owned and (target.is_file() or not exists(target))
        if owned and saved.get("sha256") == digest and self.target_digest(target) is not None:
            return target.relative_to(destination).as_posix()
        owned = owned and all(other == key or entry["target"] != previous for other, entry in self.state.items())
        if not owned:
            target = original
            if self.target_digest(target) not in (None, digest):
                target = self.unique_copy(target, digest)
        if target != original:
            self.collisions += 1
            print(f"Collision {source} → {target}")
        if self.target_digest(target) != digest:
            self.copy(source, target, data, verify, memory=True)
        self.state[key] = {"target": target.relative_to(self.shared).as_posix(), "sha256": digest}
        return target.relative_to(destination).as_posix()

    def blocked_file(self, path, violations):
        self.blocked += 1
        for line, kind in violations:
            print(f"BLOCKED {path}:{line} ({kind})")

    def memory_link(self, path, source, destination, names, blocked, verify):
        resolved = path.resolve(strict=True)
        relative = resolved.relative_to(source.resolve())
        if any(part.as_posix() in blocked for part in (relative, *relative.parents)):
            raise ValueError("link points to a blocked entry")
        link = destination / path.relative_to(source)
        if resolved.is_dir():
            target = destination / relative
            if resolved == source.resolve() or not (target.is_dir() or target in self.planned_dirs):
                raise ValueError("no safe shared directory target")
        else:
            name = names.get(relative.as_posix())
            if not name:
                raise ValueError("no safe shared file target")
            target = destination / name
        if exists(link) or link in self.planned_notes or link in self.planned_dirs:
            if same_link(link, target):
                return
            raise ValueError("shared path already exists")
        pointing_to = os.path.relpath(target, link.parent)
        print(f"Copy internal link {path} → {link}")
        if self.apply:
            verify(lambda: link.symlink_to(pointing_to, target_is_directory=resolved.is_dir()))
        else:
            self.planned_notes[link] = ""
        self.copied += 1

    def memory_index(self, source, index, names, blocked, verify):
        original = source / "MEMORY.md"
        raw = original.read_bytes() if original.is_file() and not original.is_symlink() else b""
        try:
            text = raw.decode("utf-8")
        except UnicodeError:
            self.blocked_file(original, [(1, "invalid UTF-8")])
            text = ""
        violations = list(note_violations(text, include_phone=False))
        if violations:
            self.blocked_file(original, violations)
            text = ""
        if raw and not text:
            blocked.add("MEMORY.md")
        lines = []
        for line in text.splitlines(keepends=True):
            target, span = pointer(line.rstrip("\r\n"))
            relative = normalized_link(target) if target else None
            if relative and any(part.as_posix() in blocked for part in (Path(relative), *Path(relative).parents)):
                continue
            renamed = names.get(relative)
            if renamed and renamed != relative:
                renamed = quote(renamed) if "%" in target else renamed
                line = line[:span[0]] + renamed + line[span[1]:]
            if span:
                end = span[0] + (len(renamed) if renamed and renamed != relative else span[1] - span[0])
                line = redact_phone(line[:span[0]]) + line[span[0]:end] + redact_phone(line[end:])
            else:
                line = redact_phone(line)
            lines.append(line)
        incoming = "".join(lines)
        current = self.planned_indexes.get(index)
        if current is None:
            current = index.read_bytes().decode("utf-8") if index.is_file() else ""
        if not current:
            updated = incoming
            added = len(set(pointer_targets(incoming)))
        elif incoming == current:
            return
        else:
            updated, added = append_pointers(index, incoming.splitlines(), False, current)
            prose = "".join(line for line in lines if not pointer(line.rstrip("\r\n"))[0]).strip()
            current_prose = "".join(
                line for line in current.splitlines(keepends=True) if not pointer(line.rstrip("\r\n"))[0]
            )
            if prose and prose not in current_prose:
                updated = updated.rstrip("\r\n") + f"\n\n## Migrated from {source.parent.name}\n\n{prose}\n"
        self.pointers += added
        if updated != current or (not index.is_file() and index not in self.planned_indexes):
            print(f"Merge memory index {original} → {index}")
            if self.apply:
                backup = private_memory_backup(self.shared, index)
                atomic_write(index, updated.encode("utf-8"), verify=verify, private_backup=backup)
            else:
                self.planned_indexes[index] = updated

    def memory(self, source, index):
        if same_location(source, index.parent):
            return
        if source.resolve() in index.parent.resolve().parents:
            raise ValueError(f"shared memory destination is inside {source}")
        with (index_lock(index) if self.apply else nullcontext()) as verify:
            if same_location(source, index.parent):
                return
            snapshot = memory_snapshot(source)
            counted = set()
            for _ in range(3):
                if self.copy_memory(source, index, verify, snapshot, counted):
                    print(f"Keep {source} in place because it contains blocked entries")
                    return
                if not self.apply:
                    self.link(source, index.parent, directory=True)
                    return
                verify()
                latest = memory_snapshot(source)
                if latest == snapshot:
                    def unchanged(backup):
                        expected = {(backup / path.relative_to(source), kind): status
                                    for (path, kind), status in snapshot.items()}
                        return memory_snapshot(backup) == expected

                    if self.link(source, index.parent, directory=True, check=unchanged):
                        return
                    latest = memory_snapshot(source)
                print(f"Rescan changed Claude memory {source}")
                snapshot = latest
            warn(f"Claude memory kept in place because it is still changing: {source}")
            self.link_warnings.append(source)

    def copy_memory(self, source, index, verify, snapshot, counted):
        names = {}
        blocked = set()
        links = []
        for path, kind in snapshot:
            relative = path.relative_to(source)
            if any(parent.as_posix() in blocked for parent in relative.parents):
                continue
            fresh = path not in counted
            counted.add(path)
            if kind == "unsupported":
                blocked.add(relative.as_posix())
                self.blocked_file(path, [(1, "unsupported filesystem entry")])
            elif kind == "link":
                self.assets += int(fresh and path.suffix.lower() != ".md")
                links.append(path)
            elif kind == "directory":
                self.subdirs += int(fresh)
                target = index.parent / relative
                if target in self.planned_notes or (exists(target) and (target.is_symlink() or not target.is_dir())):
                    blocked.add(relative.as_posix())
                    self.blocked_file(path, [(1, "shared directory collides with an existing file or link")])
                elif self.apply:
                    verify()
                    target.mkdir(parents=True, exist_ok=True)
                else:
                    self.planned_dirs.add(target)
            elif relative.as_posix() != "MEMORY.md":
                self.assets += int(fresh and path.suffix.lower() != ".md")
                data, violations, private = memory_payload(path)
                if violations:
                    blocked.add(relative.as_posix())
                    self.blocked_file(path, violations)
                    continue
                if private:
                    self.private += int(fresh)
                    print(f"Set metadata.share: claude-only in shared copy of {path}")
                names[relative.as_posix()] = self.copy_note(path, source, index.parent, data, verify)
        for link in links:
            relative = link.relative_to(source).as_posix()
            try:
                if relative == "MEMORY.md":
                    raise ValueError("memory index must be a regular file")
                self.memory_link(link, source, index.parent, names, blocked, verify)
            except (OSError, RuntimeError, ValueError):
                blocked.add(relative)
                self.blocked_file(link, [(1, "cannot preserve an internal link safely")])
        self.memory_index(source, index, names, blocked, verify)
        return bool(blocked)

    def summary(self):
        files, pointers = ("copied", "merged") if self.apply else ("to copy", "to merge")
        print(f"Migration summary: {self.copied} file(s) {files}, {self.pointers} pointer(s) {pointers}, "
              f"{self.collisions} collision(s), {self.mapped} mapped, {len(self.unmapped)} UNMAPPED, "
              f"{len(self.link_warnings)} symlink warning(s), {self.assets} non-.md file(s), "
              f"{self.subdirs} subdir(s), {self.blocked} BLOCKED, {self.private} claude-only")
        for path, reason in self.unmapped:
            print(f"UNMAPPED {path}: {reason}")
        if self.unmapped:
            for reason, count in sorted(Counter(reason for _, reason in self.unmapped).items()):
                print(f"  {count} folder(s): {reason}")
            print("Use migrate --map <folder>=<path> or register --local-id for a project without an origin.")
        for path in self.link_warnings:
            print(f"Symlink warning recorded for {path}")


def migrate(shared, claude, global_project, explicit_maps, apply):
    with (index_lock(shared / MIGRATION_STATE) if apply else nullcontext()) as verify:
        migration = Migration(shared, apply)
        project_root = claude / "projects"
        configs, mappings = project_maps(shared, claude)
        for entry in explicit_maps:
            folder, separator, raw_path = entry.partition("=")
            if not separator or not re.fullmatch(r"[A-Za-z0-9-]+", folder) or not raw_path:
                raise ValueError("--map expects CLAUDE-FOLDER=PATH")
            path = Path(raw_path).expanduser().resolve()
            source = project_root / folder / "memory"
            key = project_key(shared, path) if path.is_dir() else None
            if not source.is_dir() or key is None:
                raise ValueError(f"cannot map {folder}; provide a Claude memory folder and an existing project with a Git origin or registered local ID")
            destination = shared / "projects" / key.replace("/", "__")
            if source.is_symlink() and not same_location(source, destination):
                raise ValueError(f"cannot map {folder}; its existing memory link points elsewhere")
            mappings[folder] = str(path)
            print(f"Map Claude folder {folder} → {path}")
        binding = shared / "memory" / GLOBAL_SOURCE
        bindings = global_sources(shared, claude)
        config = str(claude.resolve())
        saved = bindings.get(config)
        if global_project is not None:
            selected = global_project.expanduser()
            global_path = project_root / selected if len(selected.parts) == 1 else selected.absolute()
        elif saved:
            global_path = Path(saved)
        else:
            global_path = project_root / project_folder(Path.home())
        if any(
            (project_root / entry.partition("=")[0]).resolve() == global_path.resolve()
            for entry in explicit_maps
        ):
            raise ValueError("a folder selected as global memory cannot also be mapped to a project")
        errors = migration.rules(claude)
        audited = {}
        for directory in memory_project_directories(project_root, global_path):
            source = directory / "memory"
            try:
                mapping = mappings.get(directory.name) if directory.parent == project_root else None
                key = transcript_project(shared, directory, global_path, mapping, report=True)
            except ValueError as error:
                migration.unmapped.append((directory, str(error)))
                continue
            destination = shared / "memory" if key is None else shared / "projects" / key.replace("/", "__")
            if source.is_symlink() and not same_location(source, destination):
                migration.unmapped.append((directory, "existing memory symlink points elsewhere"))
                continue
            if destination.is_symlink() and not same_location(source, destination):
                migration.unmapped.append((directory, "shared memory destination is itself a symlink"))
                continue
            if key is None:
                index = shared / "memory/MEMORY.md"
                if global_project is not None:
                    value = str(global_path.resolve())
                    if saved != value:
                        print(f"Record Claude global memory source {global_path}")
                        if apply:
                            bindings[config] = value
                            data = json.dumps(bindings, indent=2, sort_keys=True).encode("utf-8") + b"\n"
                            atomic_write(binding, data, backup=True, verify=verify)
            else:
                index = project_index(shared, key, apply, create_memory=False)
            migration.mapped += 1
            migration.memory(source, index)
            if key is not None:
                audited[str(directory.resolve())] = key
        migration.save_state(verify)
        if apply:
            audit_file = shared / AUDIT_MAPS
            audit_maps = json.loads(read_optional(audit_file) or "{}")
            if audit_maps.get(config) != audited:
                audit_maps[config] = audited
                data = json.dumps(audit_maps, sort_keys=True).encode("utf-8") + b"\n"
                atomic_write(audit_file, data, backup=True, verify=verify)
        if apply and explicit_maps:
            data = json.dumps(configs, indent=2, sort_keys=True).encode("utf-8") + b"\n"
            atomic_write(shared / PROJECT_MAPS, data, backup=True, verify=verify)
        migration.summary()
        return 2 if errors else 0


def metadata(text):
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, False
    values = {}
    nested = legacy = False
    indentation = None
    for line in lines[1:]:
        if line.strip() == "---":
            return values, legacy
        content = line.lstrip()
        if not content or content.startswith("#"):
            continue
        key, separator, value = content.partition(":")
        value = value.strip()
        value = "" if value.startswith("#") else value.split(" #", 1)[0].rstrip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]
        if not line[0].isspace():
            nested = bool(separator) and key == "metadata" and not value
            indentation = None
            if key == "metadata":
                values.clear()
            legacy = legacy or key == "type"
        elif nested:
            depth = len(line) - len(content)
            if indentation is None:
                indentation = depth
            if separator and depth == indentation and key in ("type", "share"):
                values[key] = value
    return {}, False


def secret_on(line):
    if SECRET_PREFIX.search(line) or SECRET_JWT.search(line) or SECRET_WEBHOOK.search(line):
        return True
    for match in SECRET_ASSIGNMENT.finditer(line):
        value = next(group for group in match.groups()[1:] if group is not None).rstrip(".,;)")
        trailing_words = re.search(r"[ \t]+[A-Za-z]", line[match.end():].split("#", 1)[0])
        looks_credential = not any(char.isspace() for char in value) and bool(re.search(r"[^A-Za-z-]", value))
        minimum = 4 if re.search(r"(?:password|passwd|senha(?:\s.*)?)$", match["label"], re.I) else 8
        if len(value) >= minimum and not SECRET_PLACEHOLDER.fullmatch(value) and (not trailing_words or looks_credential):
            return True
    return any(
        not SECRET_PLACEHOLDER.fullmatch(unquote(match[1]).rstrip(".,;)"))
        for pattern in (SECRET_AUTHORIZATION, SECRET_URL)
        for match in pattern.finditer(line)
    )


def redact_phone(line):
    return PHONE.sub(lambda match: (match["label"] or "") + "[phone removed]", line)


def memory_text(data):
    if b"\0" in data[:8192]:
        return None
    # Keep non-UTF-8 bytes intact if quarantine changes only the frontmatter.
    return data.decode("utf-8", errors="surrogateescape")


def read_memory_bytes(path, limit=None):
    with path.open("rb") as stream:
        prefix = stream.read(8192)
        if b"\0" in prefix:
            return None
        if limit is None:
            return prefix + stream.read()
        if os.fstat(stream.fileno()).st_size > limit:
            raise OverflowError("text file exceeds the session scan limit")
        data = prefix + stream.read(limit - len(prefix) + 1)
        if len(data) > limit:
            raise OverflowError("text file exceeds the session scan limit")
        return data


def memory_files(root):
    if not root.is_dir():
        return
    with os.scandir(root) as entries:
        children = sorted(entries, key=lambda entry: entry.name)
    for entry in children:
        name = entry.name
        if (name.startswith(".prime-context-") or re.search(r"\.bak-\d{8}-\d{6}$", name)
                or name.endswith((".lock", ".lock-reap")) or name in (GLOBAL_SOURCE, ".local-path")):
            continue
        path = Path(entry.path)
        if entry.is_dir(follow_symlinks=False):
            if os.name == "nt" and getattr(entry.stat(follow_symlinks=False), "st_reparse_tag", None) == getattr(
                stat, "IO_REPARSE_TAG_MOUNT_POINT", -1
            ):
                continue
            yield from memory_files(path)
        elif entry.is_file(follow_symlinks=False):
            yield path


def memory_documents(root):
    for path in memory_files(root):
        raw = read_memory_bytes(path)
        if raw is not None:
            yield path, memory_text(raw)


def shared_memory_roots(shared):
    yield shared / "memory"
    for project in sorted((shared / "projects").glob("*")):
        if project.is_dir() and not project.is_symlink():
            yield project


def shared_memory_violations(shared):
    for root in shared_memory_roots(shared):
        for path, text in memory_documents(root):
            note, problems = memory_verdict(path, text)
            if problems:
                yield path, text, note, problems


def memory_verdict(path, text):
    note = path.suffix.lower() in (".md", ".markdown") and path.name != "MEMORY.md"
    if text is None or (note and metadata(text)[0].get("share") == "claude-only"):
        return note, []
    return note, list(note_violations(text, include_phone=True))


def private_memory_backup(shared, path):
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    relative = path.relative_to(shared)
    return shared / ".state/backups" / relative.parent / f"{relative.name}.{uuid4().hex}.bak-{stamp}"


def quarantine_note(shared, path, original, updated, timeout):
    with index_lock(path, timeout=timeout) as verify:
        if path.read_bytes() != original:
            return False
        committed = False

        def verify_current(action):
            def commit():
                nonlocal committed
                if path.read_bytes() == original:
                    action()
                    committed = True
            verify(commit)

        atomic_write(path, updated, verify=verify_current, private_backup=private_memory_backup(shared, path))
        return committed


def quarantine(shared, apply, budget=None):
    deadline = time.monotonic() + budget if budget is not None else None
    state_file = shared / SCAN_CACHE
    try:
        state = json.loads(read_optional(state_file) or "{}") if apply else {}
    except (ValueError, OSError):
        warn("Could not read the quarantine cache; rescanning notes")
        state = {}
    if state.get("version") != SCAN_VERSION:
        state = {}
    entries = dict(state.get("entries", {}))
    resume = state.get("resume") if deadline is not None else None
    cursor = None
    paused = False
    count = 0
    remaining = False
    files = (path for root in shared_memory_roots(shared) for path in memory_files(root))
    visited = set()
    for path in files:
        key = path.relative_to(shared).as_posix()
        visited.add(key)
        if resume is not None:
            if key == resume:
                cursor, resume = resume, None
            continue
        if deadline is not None and time.monotonic() >= deadline:
            paused = True
            break
        cursor = key
        try:
            status = path.stat()
            fingerprint = [status.st_mtime_ns, status.st_size, status.st_ctime_ns, status.st_ino]
            known = entries.get(key)
            if known and known[:-1] == fingerprint:
                if known[-1] != "deferred":
                    for line, pattern in known[-1]:
                        print(f"{path}:{line}: {pattern}")
                        remaining = True
                    continue
                if deadline is not None:
                    remaining = True
                    continue
            original = read_memory_bytes(path, limit=262144 if deadline is not None else None)
            text = memory_text(original) if original is not None else None
            note, problems = memory_verdict(path, text)
            for line, pattern in problems:
                print(f"{path}:{line}: {pattern}")
            if problems and note:
                updated = private_frontmatter(text)
                if metadata(updated)[0].get("share") != "claude-only":
                    remaining = True
                    continue
                if apply:
                    if not quarantine_note(
                        shared, path, original, updated.encode("utf-8", errors="surrogateescape"),
                        0.02 if deadline is not None else 10,
                    ):
                        remaining = True
                        continue
                    entries.pop(key, None)
                    count += 1
                    continue
                problems = []
                count += 1
            remaining = remaining or bool(problems)
            entries[key] = [*fingerprint, [list(problem) for problem in problems]]
        except OverflowError:
            entries[key] = [*fingerprint, "deferred"]
            remaining = True
        except OSError:
            remaining = True
    if apply:
        if not paused:
            entries = {key: value for key, value in entries.items() if key in visited}
        updated = {"version": SCAN_VERSION, "entries": entries, "resume": cursor if paused else None}
        if updated != state:
            try:
                atomic_write(state_file, json.dumps(updated, separators=(",", ":")).encode("utf-8"))
            except OSError:
                remaining = True
    print(f"{'Quarantined' if apply else 'Would quarantine'} {count} note(s)")
    if paused:
        print("Quarantine paused; scan will resume on the next run.")
    return int(remaining)


def note_violations(text, include_phone):
    for number, line in enumerate(text.splitlines(), 1):
        if secret_on(line):
            yield number, "secret"
        if include_phone and redact_phone(line) != line:
            yield number, "phone"


def check_note(path):
    text = read(path)
    values, _ = metadata(text)
    violations = list(note_violations(text, values.get("share") != "claude-only"))
    for number, pattern in violations:
        print(f"{number}: {pattern}")
    return int(bool(violations))


